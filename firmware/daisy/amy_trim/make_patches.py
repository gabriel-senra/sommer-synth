#!/usr/bin/env python3
"""Generate a trimmed AMY patches.h containing only the patches we KEEP.

AMY's patches.h is 258 patches as text command strings:
    0-127   Juno-106 bank   (~34 KB)
    128-255 DX7 bank        (~77 KB)
    256     dpwe piano      (needs the piano partials table, which we trim)
    257     amyboard default
Removed patches become a plain 1-osc sine, so selecting one never gives
silence or a crash. Patch numbers stay the same, so code that says
"patch 18" still means Juno patch 18.

Usage: make_patches.py <amy/patches.h> <out/patches.h>
"""
import re, sys

# ── The keep-list. Edit this line to change what ships on the Daisy. ──
KEEP = set(range(0, 128))          # Juno bank only

FALLBACK, FALLBACK_OSCS = "v0w0Z", 1   # osc 0, wave 0 (SINE)

src, dst = sys.argv[1], sys.argv[2]
lines = open(src).read().splitlines()
entry = re.compile(r'(\s*/\* (\d+): .*? \*/ )"(.*)",\s*$')
out, in_oscs = [], False
for line in lines:
    m = entry.match(line)
    if m and int(m.group(2)) not in KEEP:
        line = f'{m.group(1)}"{FALLBACK}",  // trimmed'
    if line.startswith("const uint16_t patch_oscs"):
        in_oscs = True
    elif in_oscs and not line.startswith("}"):
        nums = [n for n in line.split(",") if n.strip()]
        line = ",".join(n if i in KEEP else str(FALLBACK_OSCS) for i, n in enumerate(nums)) + ","
        in_oscs = False
    out.append(line)
open(dst, "w").write("// GENERATED by firmware/daisy/amy_trim/make_patches.py — do not edit.\n" + "\n".join(out) + "\n")
